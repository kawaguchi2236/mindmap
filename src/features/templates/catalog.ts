/**
 * テンプレートの一覧（docs/要件定義.md SCR-005 / design/ハンドオフ.md `#3c`）。
 *
 * 要件は「Phase 1 では画面だけ先行してもよい」としているが、選んでも何も
 * 起きない画面を置くほうが不誠実なので、木の中身まで持たせて実際にマップを
 * 作れるようにする。とはいえ中身は**ただのテキストの入れ子**で、専用の
 * データ構造は作らない（CLAUDE.md §37）。
 *
 * ここは純粋なデータと純関数だけ。IndexedDB には触らない。
 *
 * ## 木の作り方（全テンプレート共通の約束）
 *
 * テンプレートの値は「その枠組みの正式な型」であって、例文ではない。
 * どれを選んでも同じ形になるとテンプレートの意味が無いので、階層の役割を揃える:
 *
 * - 第1階層（ルート）… その枠組みの対象。**対象と時点（期間）はここに畳む**。
 *   第2階層の末尾にメタ情報の箱を置くと、実際には最初に決まるのに最後に
 *   埋めることになり、上から順に埋めるキーボード操作と衝突する。
 * - 第2階層 … その枠組みに**必ずある箱**。並び順は「書く順番」。
 *   枠組みの通称の順（Will-Can-Must、コーネル式の紙の配置）と書く順が違うときは、
 *   **書く順を優先する**（このアプリは上から Enter / Tab で埋めていくため）。
 *   末尾には必ず**出口の箱**（次の一歩・結論・完成の定義）を置く。
 *   入口（記入の仕方）だけ手厚くて出口が無いと、木が候補リストで終わる。
 * - 第3階層 … その箱の**記入の型**（何を・どの単位で書くか）。
 *   `指標：現状 → 目標` `経験：いつ・何を・結果` のように**型を示す**こと。
 *   `打ち手 1` `3.1 画面` のような**連番**や、`思いついたこと` のような
 *   **分類名**は、何をどの単位で書くかを伝えないので置かない。
 *   分類を先に決めさせると、書く前に分類の判断を強制することになる。
 * - 第4階層 … **深さ自体が枠組みの一部である場合だけ**置く。
 *   ロジックツリーの掘り下げ、ロードマップの「成果に従属する目印」、
 *   読書メモの「引用に紐づく気づき」の3つ。それ以外は3階層で止める。
 *
 * 各枠組みで守っている作法（調べた上で型に落としたもの）:
 *
 * - SWOT: 外部環境 → 内部環境の順に洗い出し、クロス SWOT（SO/ST/WO/WT）で戦略に変える。
 *   何を決めるための分析かを先に置かないと、4つの箱を埋めるだけで終わる。
 * - ロードマップ: 日付を約束せず Now / Next / Later で並べ、機能ではなくアウトカムを書く。
 *   成功指標はアウトカムの子（1アウトカム＝1指標）。「やらないこと」は理由とセット。
 * - WBS: 成果物志向で分解する（第2階層は名詞、第3階層は動詞）。親は子の合計（100% ルール）
 *   なので、境界を「完成の定義」と「対象外」で閉じ、どの成果物にも属さない作業は
 *   「進行管理」で受ける。末端のワークパッケージは 8〜80 時間に収まる粒度にする。
 * - OKR: Objective は定性（なぜ今これかの背景とセット）、Key Results は定量で 3 つ程度。
 *   打ち手（Initiatives）は KR とは別の箱に置き、どの KR に効くかを書かせる。
 * - ブレスト: 発散（批判しない・量優先・便乗）と収束（束ねて選ぶ）を分ける。
 *   発散中は分類させない。便乗は元の案の子にする。
 * - 読書メモ: 引用はページ番号付きで原文のまま、気づきはその引用の子、要約は自分の言葉で。
 *   持ち込んだ問いへの答えを、本の要約とは別の箱に置く。
 * - 学習ノート: コーネル式の3領域。書く順は ノート →（後から）キーワードと問い → サマリー。
 * - キャリア: Can（事実）から書き始め、Will を掘り、Must で制約を置く。
 *   「やりたいことが分からないから棚卸しをする」人が Will で止まらないようにする。
 * - ロジックツリー: 1本のツリーは1つの型（ここは Why ツリー）。同じ階層は切り口を揃え、
 *   子には問いではなく**答え（原因）**を書く。漏れの受け皿は残りかす用であって、
 *   主要因を押し込む箱ではないので、切り口は3本以上立てる。
 */
